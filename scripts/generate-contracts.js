function normalizePayloadType(payloadType) {
  return String(payloadType).replace(/\s+/g, ' ').trim();
}

function parseManifestParameterDescriptor(parameterDescriptor) {
  const descriptor = String(parameterDescriptor || '').trim();
  const match = descriptor.match(/^(\.\.\.)?([A-Za-z_$][A-Za-z0-9_$]*)(\?)?\s*:\s*(.+)$/);
  if (!match) return { signature: normalizePayloadType(descriptor || 'unknown'), type: 'unknown' };
  const [, rest = '', name, optional = '', parameterType] = match;
  const normalizedType = normalizePayloadType(parameterType);
  return { signature: `${rest}${name}${optional}: ${normalizedType}`, type: normalizedType };
}

function manifestParameterSignatures(entry) {
  return (entry.parameters || entry.request || []).map((descriptor) => parseManifestParameterDescriptor(descriptor).signature);
}

function createInvokeManifestSignature(entry) {
  return `(${manifestParameterSignatures(entry).join(', ')}): Promise<${normalizePayloadType(entry.response || 'unknown')}>`;
}

function createSubscriptionManifestSignature(entry) {
  const payloadType = normalizePayloadType(entry.payload || 'unknown');
  const callbackSignature = payloadType === 'void' ? 'callback: () => void' : `callback: (payload: ${payloadType}) => void`;
  return `(${callbackSignature}): ${normalizePayloadType(entry.return || 'Unsubscribe')}`;
}

function apiInterfaceName(apiName) {
  return `${apiName[0].toUpperCase()}${apiName.slice(1)}`;
}

function normalizeRegistryMetadataValue(value) {
  return String(value || '').trim();
}

function derivePublicMethodName(entry) {
  return normalizeRegistryMetadataValue(entry.factoryMethod || entry.method);
}

function createTypeImportLines(ipcManifest) {
  const typeReferenceIgnoreList = new Set(
    'Array ArrayBuffer Promise Record Readonly ReadonlyArray Unsubscribe boolean false never null number object string true undefined unknown void'.split(' ')
  );

  function collectTypeReferencesFromTypeText(typeText) {
    return [...normalizePayloadType(typeText).matchAll(/\b[A-Za-z_$][A-Za-z0-9_$]*\b/g)]
      .map((match) => match[0])
      .filter((typeName) => !typeReferenceIgnoreList.has(typeName));
  }

  function collectTypeReferencesFromManifestParameters(entry) {
    return (entry.parameters || entry.request || []).flatMap((descriptor) =>
      collectTypeReferencesFromTypeText(parseManifestParameterDescriptor(descriptor).type)
    );
  }

  const typeReferences = [...new Set(
    ipcManifest.namespaces.flatMap((namespace) => [
      ...(namespace.invoke || []).flatMap((entry) => collectTypeReferencesFromManifestParameters(entry)),
      ...(namespace.invoke || []).flatMap((entry) => collectTypeReferencesFromTypeText(entry.response || 'unknown')),
      ...(namespace.subscriptions || []).flatMap((entry) => collectTypeReferencesFromTypeText(entry.payload || 'unknown')),
      ...(namespace.subscriptions || []).flatMap((entry) => collectTypeReferencesFromTypeText(entry.return || 'Unsubscribe'))
    ])
  )].sort();

  return typeReferences.length === 0
    ? []
    : [
        'import type {',
        ...typeReferences.map((typeName, index) => `  ${typeName}${index === typeReferences.length - 1 ? '' : ','}`),
        "} from '@prismgb/ipc';",
        ''
      ];
}

function generatePreloadDeclarations(ipcManifest) {
  const lines = [
    '// Generated by PrismGB tooling.',
    '// Source: src/shared/ipc/ipc.manifest.json',
    '',
    ...createTypeImportLines(ipcManifest),
    'export {};',
    '',
    'type Unsubscribe = () => void;',
    ''
  ];

  for (const namespace of ipcManifest.namespaces) {
    lines.push(`interface ${apiInterfaceName(namespace.apiName)} {`);
    for (const method of namespace.exposedMethods) {
      const invokeEntries = (namespace.invoke || []).filter((entry) => derivePublicMethodName(entry) === method);
      const subscriptionEntries = (namespace.subscriptions || []).filter((entry) => derivePublicMethodName(entry) === method);
      if (invokeEntries.length === 1 && subscriptionEntries.length === 0) {
        lines.push(`  ${method}${createInvokeManifestSignature(invokeEntries[0])};`);
        continue;
      }
      if (subscriptionEntries.length === 1 && invokeEntries.length === 0) {
        lines.push(`  ${method}${createSubscriptionManifestSignature(subscriptionEntries[0])};`);
        continue;
      }
      lines.push(`  ${method}(...args: unknown[]): unknown;`);
    }
    lines.push('}', '');
  }

  lines.push('declare global {', '  interface Window {');
  for (const namespace of ipcManifest.namespaces) {
    lines.push(`    ${namespace.apiName}?: ${apiInterfaceName(namespace.apiName)};`);
  }
  lines.push('  }', '');

  for (const namespace of ipcManifest.namespaces) {
    lines.push(`  var ${namespace.apiName}: ${apiInterfaceName(namespace.apiName)} | undefined;`);
  }
  lines.push('}', '');

  return lines.join('\n');
}

